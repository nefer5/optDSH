from __future__ import annotations

import json
import unittest

import support
from archkit.state import ReviewState

WIN = "D:" + "\\work\\file.txt"


class ScanCliTests(unittest.TestCase):
    def setUp(self) -> None:
        self.proj = support.TempProject(git=True)
        self.addCleanup(self.proj.close)
        self.proj.write("src/app/core.py", "def f():\n    return 1\n")
        self.proj.write("src/app/old.py", f'P = r"{WIN}"\n')
        self.proj.commit()

    def test_json_structure_and_exit_code(self) -> None:
        code, data = self.proj.scan_json()
        self.assertEqual(code, 1)
        self.assertEqual(set(data), {"root", "scope", "findings", "summary", "fingerprint"})
        self.assertEqual(data["scope"], "full")
        self.assertIsNone(data["fingerprint"])
        finding = data["findings"][0]
        self.assertEqual(set(finding), {"id", "severity", "path", "line", "message"})
        self.assertEqual((finding["id"], finding["path"], finding["line"]),
                         ("ARCH-HARDCODE", "src/app/old.py", 1))
        self.assertEqual(data["summary"]["error"], 1)

    def test_changed_scope_only_new_lines(self) -> None:
        code, data = self.proj.scan_json("--changed")
        self.assertEqual((code, data["findings"]), (0, []))
        self.proj.write("src/app/core.py", "def f():\n    return 2\n")
        self.proj.write("src/app/old.py", f'P = r"{WIN}"\nQ = 1\n')
        self.proj.write("src/app/new.py", "URL = 'https://api.service.io'\n")
        code, data = self.proj.scan_json("--changed")
        self.assertEqual(data["scope"], "changed")
        self.assertEqual(code, 0)
        self.assertEqual([(f["id"], f["path"]) for f in data["findings"]],
                         [("ARCH-HARDCODE", "src/app/new.py")])
        self.assertEqual(data["summary"]["changed_files"], 3)
        self.assertRegex(data["fingerprint"], r"^[0-9a-f]{64}$")

    def test_record(self) -> None:
        self.proj.write("src/app/new.py", "X = 1\n")
        code, data = self.proj.scan_json("--changed", "--record")
        self.assertEqual(code, 0)
        self.assertTrue(data["recorded"])
        state = ReviewState.load(self.proj.root)
        self.assertEqual(state.status_of(data["fingerprint"]), "reviewed")
        self.assertTrue(str(state.path).replace("\\", "/").endswith(".git/software-architect/state.json"))

    def test_record_without_changes(self) -> None:
        self.proj.write("src/app/old.py", "P = 1\n")
        self.proj.commit()
        code, out, _ = self.proj.scan("--record")
        self.assertEqual(code, 0)
        self.assertIn("未记录", out)

    def test_markdown_and_usage_errors(self) -> None:
        code, out, _ = self.proj.scan()
        self.assertEqual(code, 1)
        self.assertIn("## 架构扫描（全量）", out)
        self.proj.enable("[limits]\nmax_line = 3\n")
        code, out, err = self.proj.scan("--json")
        self.assertEqual((code, out), (2, ""))
        self.assertIn("max_line", err)
        code, _, _ = self.proj.scan("--bogus")
        self.assertEqual(code, 2)

    def test_no_commit_repo_all_new(self) -> None:
        proj = support.TempProject(git=True)
        self.addCleanup(proj.close)
        proj.write("tool.py", "print(1)\n")
        proj.write("lib/a.py", "X = 1\n")
        code, data = proj.scan_json("--changed")
        self.assertEqual(data["summary"]["changed_files"], 2)
        self.assertIn("ARCH-ROOT-SCRIPT", [f["id"] for f in data["findings"]])

    def test_non_git_directory(self) -> None:
        proj = support.TempProject(git=False)
        self.addCleanup(proj.close)
        proj.write("node_modules/x/index.js", "const u = 'https://a.service.io';\n")
        proj.write("src/a.py", "X = 1\n")
        code, data = proj.scan_json()
        self.assertEqual(code, 0)
        self.assertEqual(data["summary"]["files_scanned"], 1)
        json.dumps(data)

class DistributionManagedFilesTests(unittest.TestCase):
    """Copies generated by expert-distribute are neither scanned nor counted as changes."""

    def test_receipt_listed_files_are_skipped(self) -> None:
        proj = support.TempProject(git=True)
        self.addCleanup(proj.close)
        proj.write("src/app/core.py", "def f():\n    return 1\n")
        proj.commit()
        generated = ".agents/resources/x/kit/scripts/tool.py"
        proj.write(generated, f'P = r"{WIN}"\n')
        proj.write(".agents/skills/s/SKILL.md", "# s\n")
        proj.write(".agents/.distribution/state.json", json.dumps({"schema_version": 1, "files": {
            generated: {"sha256": "0"}, ".agents/skills/s/SKILL.md#x": {"sha256": "0"}}}))
        code, data = proj.scan_json("--changed")
        self.assertEqual((code, data["findings"]), (0, []))
        self.assertIsNone(data["fingerprint"])

if __name__ == "__main__":
    unittest.main()
