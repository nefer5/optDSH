"""File discovery, classification and cached text reading."""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from pathlib import Path

from . import gitio
from .config import Config
from .globs import GlobSet

MAX_FILE_BYTES = 1024 * 1024
BINARY_SNIFF_BYTES = 8192

BUILTIN_SKIP_DIRS = frozenset({
    ".git", ".hg", ".svn", "node_modules", ".venv", "venv", "dist", "build",
    "__pycache__", ".mypy_cache", ".pytest_cache", ".ruff_cache", ".tox",
    ".next", ".nuxt", ".turbo", ".cache", "coverage", ".gradle",
})
VENDOR_DIRS = frozenset({"vendor", "third_party", "3rdparty"})
GENERATED_DIRS = frozenset({"generated", "__generated__", "gen", "out"})

PY_EXT = frozenset({".py", ".pyi"})
TS_EXT = frozenset({".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".cts"})
CPP_EXT = frozenset({".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx", ".ipp", ".inl"})
OTHER_CODE_EXT = frozenset({
    ".ps1", ".psm1", ".sh", ".bash", ".zsh", ".bat", ".cmd", ".go", ".rs", ".java",
    ".kt", ".cs", ".rb", ".php", ".lua", ".pl", ".swift", ".scala", ".vue", ".svelte",
})
CODE_EXT = PY_EXT | TS_EXT | CPP_EXT | OTHER_CODE_EXT
LOCK_NAMES = frozenset({
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml",
    "poetry.lock", "Pipfile.lock", "Cargo.lock", "uv.lock", "composer.lock",
    "Gemfile.lock", "go.sum", "bun.lock", "bun.lockb", "packages.lock.json",
})


def suffix(path: str) -> str:
    """Lower-case extension like PurePosixPath.suffix (hot path: plain string ops)."""
    name = path.rsplit("/", 1)[-1]
    dot = name.rfind(".")
    return name[dot:].lower() if 0 < dot < len(name) - 1 else ""


def basename(path: str) -> str:
    return path.rsplit("/", 1)[-1]


def is_code(path: str) -> bool:
    return suffix(path) in CODE_EXT


def is_lock(path: str) -> bool:
    return basename(path) in LOCK_NAMES or path.endswith(".lock")


def dir_parts(path: str) -> list[str]:
    return path.split("/")[:-1]


def in_dirs(path: str, names: frozenset[str] | set[str]) -> bool:
    return any(part in names for part in dir_parts(path))


def is_minified(path: str) -> bool:
    name = basename(path)
    return ".min." in name or name.endswith(".bundle.js")


# Expert-distribution receipts: every listed file is a generated copy, not project source.
DISTRIBUTION_DIR = ".agents/.distribution/"
DISTRIBUTION_STATE = DISTRIBUTION_DIR + "state.json"


def managed_paths(root: Path | None) -> frozenset[str]:
    """Paths generated by expert-distribute (receipt keys may carry a ``#expert`` suffix)."""
    if root is None:
        return frozenset()
    try:
        data = json.loads((root / DISTRIBUTION_STATE).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return frozenset()
    files = data.get("files") if isinstance(data, dict) else None
    if not isinstance(files, dict):
        return frozenset()
    return frozenset(key.split("#", 1)[0].replace("\\", "/") for key in files if isinstance(key, str))


@dataclass
class FileFilter:
    """Combines built-in skip dirs, distribution-managed files and ``[ignore] globs``."""

    ignore: GlobSet
    managed: frozenset[str] = frozenset()

    @classmethod
    def from_config(cls, cfg: Config, root: Path | None = None) -> "FileFilter":
        return cls(GlobSet.compile(list(cfg.ignore_globs)), managed_paths(root))

    def accepts(self, path: str) -> bool:
        if in_dirs(path, BUILTIN_SKIP_DIRS) or path.startswith(DISTRIBUTION_DIR) or path in self.managed:
            return False
        return not self.ignore.match(path)


def _walk(root: Path) -> list[str]:
    out: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in BUILTIN_SKIP_DIRS)
        rel_dir = Path(dirpath).relative_to(root).as_posix()
        prefix = "" if rel_dir == "." else rel_dir + "/"
        out.extend(prefix + name for name in sorted(filenames))
    return out


def list_files(root: Path, flt: FileFilter, is_git: bool) -> list[str]:
    """Tracked + untracked (not ignored) files that exist on disk, POSIX relative."""
    if is_git:
        raw = gitio.run_git(root, ["ls-files", "-co", "--exclude-standard", "-z"])
        candidates = sorted(set(gitio.split_z(raw or b"")))
        paths = [p for p in candidates if flt.accepts(p) and (root / p).is_file()]
    else:
        paths = [p for p in _walk(root) if flt.accepts(p)]
    return paths


@dataclass
class FileStore:
    """Per-scan cache of decoded text; large and binary files read as None."""

    root: Path
    _cache: dict[str, str | None] = field(default_factory=dict)
    skipped: set[str] = field(default_factory=set)

    def text(self, path: str) -> str | None:
        if path in self._cache:
            return self._cache[path]
        value = self._load(path)
        self._cache[path] = value
        if value is None:
            self.skipped.add(path)
        return value

    def _load(self, path: str) -> str | None:
        full = self.root / path
        try:
            if full.stat().st_size > MAX_FILE_BYTES:
                return None
            data = full.read_bytes()
        except OSError:
            return None
        if b"\0" in data[:BINARY_SNIFF_BYTES]:
            return None
        text = data.decode("utf-8", "replace")
        return text[1:] if text.startswith("\ufeff") else text

    def lines(self, path: str) -> list[str] | None:
        text = self.text(path)
        return None if text is None else text.splitlines()
